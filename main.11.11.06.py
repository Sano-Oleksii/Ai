import numpy as np
# Подключаем чтение чисел из текстового представления.
from sklearn.metrics.pairwise import cosine_similarity
# Подключаем сравнение восстановленного вектора с запросом.
line = "0.8 0.6;Доставка; условия"
# Создаем короткую учебную запись с дополнительной точкой с запятой в тексте.
parts = line.split(";", 1)
# Разделяем запись только по первой точке с запятой.
chunk_vector = np.fromstring(parts[0], sep=" ")
# Превращаем строку 0.8 0.6 в числовой массив.
query_vector = np.array([1.0, 0.0])
# Создаем вектор запроса той же размерности.
score = cosine_similarity([query_vector], [chunk_vector])[0][0]
# Вычисляем одну оценку и извлекаем ее из таблицы.
result = (parts[1], float(score))
# Связываем восстановленный текст с его оценкой сходства.
print(parts[1])
# Проверяем, что точка с запятой внутри текста сохранилась.
print(chunk_vector.tolist())
# Показываем восстановленные числовые координаты.
print(f"{result[1]:.3f}")
